#!/usr/bin/env python3
"""Generate kokoro/include/kok_vocab.h from the Paradee config.json.

Paradee's tokenizer maps one misaki phoneme character to an id (178 symbols).
The runtime's G2P wraps the plugin's existing espeak-free misaki lexicon G2P
(sanotts/nano_lex_g2p.c) and maps its phoneme string through this table, so the
table has to be generated rather than hand-copied.

Usage: python3 kokoro/tools/gen_vocab.py kokoro/model/config.json kokoro/include/kok_vocab.h
"""
import argparse
import json


def c_escape(s):
    out = ""
    for ch in s:
        if ch == "\\":
            out += "\\\\"
        elif ch == '"':
            out += '\\"'
        else:
            out += ch
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("config", help="Paradee config.json (has vocab and n_token)")
    ap.add_argument("out", help="header to write")
    args = ap.parse_args()

    cfg = json.load(open(args.config, encoding="utf-8"))
    vocab = cfg["vocab"]
    n_token = int(cfg.get("n_token", 178))
    entries = sorted(vocab.items(), key=lambda kv: kv[1])

    lines = [
        "/* generated by kokoro/tools/gen_vocab.py from the Paradee config.json;",
        f" * {len(entries)} misaki phoneme symbols, n_token {n_token} */",
        "#ifndef KOK_VOCAB_H",
        "#define KOK_VOCAB_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define KOK_VOCAB_N_TOKEN {n_token}",
        f"#define KOK_VOCAB_N {len(entries)}",
        "static const struct { const char *sym; int32_t id; } KOK_VOCAB[] = {",
    ]
    for sym, idx in entries:
        lines.append(f'    {{"{c_escape(sym)}", {idx}}},')
    lines += ["};", "", "#endif"]
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}: {len(entries)} symbols, n_token {n_token}")


if __name__ == "__main__":
    main()
